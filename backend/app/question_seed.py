def _difficulty(index: int, total: int) -> str:
    ratio = index / max(1, total - 1)
    if ratio < 0.3:
        return "beginner"
    if ratio < 0.8:
        return "intermediate"
    return "advanced"


def seed_questions(db: Session) -> None:
    existing = {body for (body,) in db.query(Question.body).all()}
    added = False
    for domain in DOMAIN_ORDER:
        questions = DOMAINS[domain]
        for index, body in enumerate(questions):
            if body in existing:
                continue
            db.add(
                Question(
                    category=domain,
                    difficulty=_difficulty(index, len(questions)),
                    body=body,
                    hint="",
                    tags=[domain],
                    position=index,
                )
            )
            added = True
    if added:
        db.commit()
